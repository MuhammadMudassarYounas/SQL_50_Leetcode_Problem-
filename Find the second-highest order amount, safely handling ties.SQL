SELECT MAX(AMOUNT) AS ORDER_AMOUNT
FROM ORDERS
WHERE AMOUNT < (
    SELECT MAX(AMOUNT)
    FROM ORDERS
);




SELECT CUSTOMER_NAME, AMOUNT AS ORDER_AMOUNT
FROM ORDERS
WHERE AMOUNT = (
    SELECT MAX(AMOUNT)
    FROM ORDERS
    WHERE AMOUNT < (
        SELECT MAX(AMOUNT)
        FROM ORDERS
    )
);


SELECT CUSTOMER_NAME, AMOUNT AS ORDER_AMOUNT
FROM (
    SELECT CUSTOMER_NAME,
           AMOUNT,
           DENSE_RANK() OVER (ORDER BY AMOUNT DESC) AS RNK
    FROM ORDERS
) T
WHERE RNK = 2;